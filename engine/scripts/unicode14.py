"""Write `litmus-engine/src/unicode14.rs`: the code point ranges assigned in Unicode 14.0.

Hugging Face `tokenizers` 0.22 normalizes and pre-tokenizes with Unicode 14.0 tables, and the Rust crates carry
newer ones; the engine treats a character assigned later as unassigned, which is what `tokenizers` does. Needs a
Python whose `unicodedata` is 14.0 (Python 3.11).

    python scripts/unicode14.py
"""

from __future__ import annotations

import os
import unicodedata

from pathlib import Path


def ranges() -> list[tuple[int, int]]:
    spans, start = [], None
    for code in range(0x110000):
        assigned = unicodedata.category(chr(code)) != "Cn"
        if assigned and start is None:
            start = code
        if not assigned and start is not None:
            spans.append((start, code - 1))
            start = None
    if start is not None:
        spans.append((start, 0x10FFFF))
    return spans


def main() -> None:
    assert unicodedata.unidata_version == "14.0.0", f"needs Unicode 14.0 data, this Python has {unicodedata.unidata_version}"
    spans = ranges()
    lines = [
        "//! Code point ranges assigned in Unicode 14.0, the version of Hugging Face `tokenizers` 0.22's tables.",
        "//! Generated by `scripts/unicode14.py` from Python 3.11's `unicodedata`; do not edit.",
        "",
        f"pub static ASSIGNED: [(u32, u32); {len(spans)}] = [",
    ]
    for index in range(0, len(spans), 6):
        lines.append("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in spans[index : index + 6]))
    lines += ["];", ""]
    target = Path(__file__).resolve().parent.parent / "litmus-engine" / "src" / "unicode14.rs"
    temporary = target.with_suffix(".rs.partial")
    temporary.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    os.replace(temporary, target)
    print(f"{target}: {len(spans)} ranges")


if __name__ == "__main__":
    main()
